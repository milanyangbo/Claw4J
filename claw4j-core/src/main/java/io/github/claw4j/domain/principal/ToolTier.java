package io.github.claw4j.domain.principal;

/**
 * 能力档位：一个工具**最低**需要哪一档，以及一个部署**允许**到哪一档（P09）。
 *
 * <p>它回答的是"这个部署有哪些工具"，与 {@link ToolPermission} 回答的"这个人能不能调"
 * 是两件事（ADR-0020 裁决两者正交）。档位是部署决定，改一次要重启；
 * 权限是人事决定，按身份走。合并成一个维度会让"换档位"变成一次权限重排——
 * 而这两件事的变更节奏本来就不一样。
 *
 * <p><b>四档是累进的，不是并列的集合</b>：{@code MINIMAL < MESSAGING < CODING < FULL}，
 * 每个工具只声明它最低需要哪一档，部署选一档，声明档不高于部署档的工具才进清单。
 * 用"最低档"而不是"允许的档位集合"，是因为后者要求每个工具回答四次"我在不在这一档"，
 * 而答案之间有四种可能互相矛盾，配错了没有任何地方能发现。累进只有一个值，
 * 值本身就能被穷举校验。
 *
 * <p>累进的代价写在明处：{@code CODING} 档必然也包含消息类与数据类工具，
 * 做不出"只跑脚本、不许读消息"的部署。这类组合目前没有真实需求，
 * 而它一旦出现，正确的解法是加 deny 分组（{@link ToolProfile}），不是把档位改成集合。
 *
 * <p>档位的分配口径（哪个工具属于哪一档）不在这里，由提供工具的模块声明：
 * 只有它自己知道那个工具会碰到什么（与 {@link ToolPermissionRegistry} 同一个理由）。
 */
public enum ToolTier {

    /**
     * 只跟自己和对话有关：检索元工具、读自己的进程状态、外置计划、回忆本会话。
     *
     * <p>不碰外部世界、不碰业务数据。一个"只想让它能聊天并且别忘了刚才说了什么"的部署选这一档。
     */
    MINIMAL,

    /**
     * 加消息类与业务只读：查表、发消息、用技能、派给子 Agent、定时任务。
     *
     * <p>企业最常见的落地档位——"只做消息与问答，不许在这里跑代码"。
     */
    MESSAGING,

    /**
     * 加代码类：跑脚本、交脚本草稿。
     *
     * <p>这一档之所以单独存在，就是为了让 {@link #MESSAGING} 能真的把
     * {@code run_script} 拿掉，而不是靠"不给这个动作"把读消息一起卡住。
     */
    CODING,

    /**
     * 全部，含接入的外部 MCP 工具。
     *
     * <p>外部 server 的能力清单是运行时从远端拉来的，部署者没有机会逐条审过，
     * 所以它们只在最宽的这一档出现——这是"最不可控的东西放在最松的档"，
     * 而不是"默认全开"。
     */
    FULL;

    /**
     * 这个部署档是否包含声明为 {@code required} 的工具。
     *
     * <p>比较的是序号而不是写四行 {@code switch}：档位是累进的这条语义只该有一个表达，
     * 用 switch 写的话，加第五档时漏掉一个分支的表现是"那个工具在任何档都不出现"，
     * 没有任何地方会报错。
     */
    public boolean allows(ToolTier required) {
        return required != null && required.ordinal() <= ordinal();
    }
}
