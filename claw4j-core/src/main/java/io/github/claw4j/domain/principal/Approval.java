package io.github.claw4j.domain.principal;

/**
 * 一次工具调用除了"能不能"，还有"要不要人先批"（ADR-0007 的第三个分量，P01）。
 *
 * <p>它和鉴权是两件事，不是鉴权的另一种结果：{@link #REQUIRED} 的动作，有权限的人也要等一次
 * 批准；而没权限的人就算拿到批准也照样被拦——批准记录回答"有人同意过"，不回答"这个人能不能
 * 干"。
 *
 * <p>默认 {@link #NONE}。审批只加在真正有副作用的动作上（跑脚本、发邮件、交脚本草稿），不给
 * "读一下"：加错方向的代价不对等——"读"被要求审批，每次查询都卡在等人点按钮的地方，上线当天
 * 就会被要求关掉，最后连本该审批的也一起没了。
 */
public enum Approval {

    /** 直接执行，不过第二道门。 */
    NONE,

    /** 先过鉴权，再要一条仍然有效的批准记录，两条都满足才执行。 */
    REQUIRED
}
