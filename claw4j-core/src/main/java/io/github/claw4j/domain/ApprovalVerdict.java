package io.github.claw4j.domain;

/**
 * 一次审批决定的结局（P02、P03）。
 *
 * <p>结论只有同意与拒绝，但要回答的情形不止两种：这条不存在、这条已经过期、这条已经有结论了、
 * 你不在审批人名单里、这是你自己的请求。后几种不是错，而是"你点的这个按钮已经不作数了"或
 * "这个按钮不该由你点"。点按钮的人要能分别听见这几句（"让他重新发起"、"这条已经批过了"、
 * "去找别人批"是完全不同的下一步），所以它们各有各的名字，而不是合并成一句"操作失败"。
 *
 * <p>不放在 {@code domain.port} 里：那个包只放契约（接口与 record），枚举是带实现的类型。
 * 这是机器守的边界，不是文风偏好——{@code CoreBoundariesTest} 会红。
 */
public enum ApprovalVerdict {

    /** 批了，而且那件事已经接着往下做了。 */
    GRANTED,

    /** 拒了，理由已经回灌给模型。 */
    DENIED,

    /** 没有这个编号。 */
    NOT_FOUND,

    /** 有过，但已经过了有效期。不是错误——"批得太晚"本来就是这件机制要处理的事。 */
    EXPIRED,

    /** 已经有人定过结论了。再点一次不该翻案，也不该被当成第一次。 */
    ALREADY_DECIDED,

    /**
     * 这个人不在审批人名单里（P03）。
     *
     * <p>与"没有权限"是同一类答案、不同的一句话：他不是"批不了这一条"，是"任何一条都批不了"，
     * 下一步是去找一个名单里的人，而不是去猜这一条哪里不对。
     */
    NOT_APPROVER,

    /**
     * 提问人想批自己的请求（P03）。
     *
     * <p>单独一格而不是并进 {@link #NOT_APPROVER}：他可能就在名单里——"你是审批人，
     * 但这件事是你自己提的"。混成一句"你不能批"，下一个人会去翻名单找自己名字拼错没有，
     * 而真正的原因是这次请求该由别人点头。自批也不落结论：那条请求仍然挂着等人批。
     */
    SELF_APPROVAL
}
