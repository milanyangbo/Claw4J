-- 额度挂目标，不挂会话，更不挂 run（ADR-0027 决定五）。
--
-- "这段对话一共能烧多少"这个问法是本项目的自造物。OpenClaw 里没有会话级额度表：
-- 成本上限是 goal 上的 token budget（create_goal 的 token_budget，用完进 budget_limited），
-- 失控保护是 agents.defaults.timeoutSeconds（默认 48 小时），并发上限是 maxConcurrent。
-- 额度是**目标的属性**：一件有终点的事带一份预算，用完了 resume 开新窗口；
-- 一段对话本身没有"额度"这回事。
--
-- 所以 V16 建的这张表连同它的三项累计一起去掉：
--   * token → conversation_goal.tokens_used / token_budget（V20 已建列，本票开始记账）
--   * 工具调用次数 → 一轮之内的熔断（claw4j.agent.tool-call-limit），不改任何持久状态
--   * 耗时 → 只进指标，不进库（"这件事花了多久"是一次观测，不是一条要留存的状态）
--
-- 表直接 drop，不做数据迁移：一行"某段会话曾经用掉多少"在新形状里没有主人。
-- 历史用量要查的话，在 audit_event 的 agent.run.finished 上（票 01 已经把 token 带上）。
drop table if exists claw4j_run.agent_session_budget;
