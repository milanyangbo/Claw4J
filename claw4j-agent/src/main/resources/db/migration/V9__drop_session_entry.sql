-- 旧会话表退役：删 session_entry，清 ai_session 的历史行（ADR-0029）。
--
-- V8 建好了新的一组（节点 / 段 / 通道身份 / 绑定），代码这一版也切过去了，所以这里收掉旧的。
--
-- 为什么直接清而不是迁移：键的形状变了——私聊默认并进一个人的主会话（dmScope: main），
-- 而旧行是按 owner + 通道 + chatId 一行一条。把同一个人的多条通道行合并成 main 那一行，
-- 必然丢行（同一段历史在两条通道上各有几句），比清干净更糟。用户 2026-11-10 裁决：直接清。
--
-- 清了之后的现象是"部署之后所有人的记忆从零开始"。这是有意的：留着旧行的现象更糟——
-- 库里看得到、应用里读不到，排查时会被当成"迁移丢了数据"。
--
-- **不可逆**。生产库升级前先备份。

delete from claw4j_session.ai_session;

drop table if exists claw4j_session.session_entry;
