-- 事件条件意图：遇到才做，不排时钟（ADR-0036）。
--
-- 列逐项对齐 OpenClaw 的 standing_intents（src/state/openclaw-agent-schema.sql）：
--   id / description / trigger_keywords / trigger_embedding / channel_scope / sender_scope /
--   creator_sender / status（六态）/ expires_at / max_fires / fire_count / cooldown_seconds /
--   last_fired_at / created_at / source_session_id
-- 两处偏离：
--   1) 加 owner：它每个 agent 一个库，owner 由库隐含；我们一个库多租户，只能显式写；
--   2) trigger_embedding 建列不写：当前只做关键词匹配，将来要开只改写入与匹配两条路径。
create table if not exists claw4j_session.standing_intents (
    intent_key        bigint       generated by default as identity primary key,
    -- 对外标识，独立于主键：模型报编号时用它，别人的编号猜中了也改不了 owner。
    id                varchar(64)  not null unique,
    owner             varchar(96)  not null,
    description       text         not null,
    -- 逗号或分号分段的触发词；整词匹配，含 CJK 的词按子串匹配。
    trigger_keywords  text         not null,
    -- 预留：当前恒为 null（见 ADR-0036 决定一）。
    trigger_embedding text,
    -- 空表示"任意频道 / 任意人"。
    channel_scope     varchar(96),
    sender_scope      varchar(96),
    creator_sender    varchar(96)  check (creator_sender is null
                                          or length(btrim(creator_sender)) > 0),
    -- 六态闭合词表，与它一致：pending / armed / fired / done / cancelled / expired。
    status            varchar(16)  not null check (status in
                        ('pending', 'armed', 'fired', 'done', 'cancelled', 'expired')),
    expires_at        timestamptz  not null,
    max_fires         int          not null check (max_fires > 0),
    fire_count        int          not null default 0 check (fire_count >= 0),
    cooldown_seconds  int          not null default 86400 check (cooldown_seconds >= 0),
    last_fired_at     timestamptz,
    created_at        timestamptz  not null,
    -- 只是出处，不参与作用域判定（见 ADR-0036 决定二）。
    source_session_id varchar(255)
);

create index if not exists standing_intents_lifecycle
    on claw4j_session.standing_intents (status, expires_at);
create index if not exists standing_intents_scope
    on claw4j_session.standing_intents (owner, channel_scope, sender_scope);
