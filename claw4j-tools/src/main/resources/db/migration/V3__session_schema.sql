-- 会话记忆的表（ADR-0005：一个 Postgres 三种存储，靠 schema 分开）。
-- 业务数据在 business，会话在 claw4j_session，谁都不会跟谁抢表名。
--
-- 表结构抄自 spring-ai-session-jdbc 0.10.0 自带的
-- org/springframework/ai/session/jdbc/schema-postgresql.sql，表名保持原样（不带前缀），
-- 但**建表语句必须写全限定名**：这段 SQL 是 Flyway 跑的，Flyway 连的是默认 search_path，
-- 不写前缀表就会落到 public。运行时查询反而不带前缀——那条连接由
-- SessionMemoryConfiguration 单独开，URL 上带着 currentSchema=claw4j_session。
-- 建的时候限定、查的时候不限定，两边的落点因此是一致的，且都不依赖"当前 schema 是什么"。
-- 代价要记账：升级 spring-ai-session 时，如果官方改了表结构，这个文件要跟着改一次。
-- 换来的好处是建表只有 Flyway 一个入口 —— 官方自动配置那个 initializer 默认只在
-- 嵌入式数据库上跑，在 Postgres 上它什么都不做，靠它就等于"以为建了其实没建"。
create schema if not exists claw4j_session;

create table if not exists claw4j_session.ai_session (
    id            varchar(255) not null primary key,
    user_id       varchar(255) not null,
    created_at    timestamp    not null,
    expires_at    timestamp,
    metadata      text,
    event_version bigint       not null default 0
);

create index if not exists idx_ai_session_user_id
    on claw4j_session.ai_session (user_id);

create index if not exists idx_ai_session_expires_at
    on claw4j_session.ai_session (expires_at);

create table if not exists claw4j_session.ai_session_event (
    seq             bigint       generated by default as identity,
    id              varchar(255) not null primary key,
    session_id      varchar(255) not null,
    "timestamp"     timestamp    not null,
    message_type    varchar(20)  not null,
    message_content text,
    message_data    text,
    synthetic       boolean      not null default false,
    archived        boolean      not null default false,
    -- 0.10.0 起不再使用（分支功能已移除），留着是为了不让已有库升级失败
    branch          varchar(500),
    metadata        text,
    constraint fk_ai_session_event_session
        foreign key (session_id) references claw4j_session.ai_session (id) on delete cascade
);

create index if not exists idx_ai_session_event_session_seq
    on claw4j_session.ai_session_event (session_id, seq);
